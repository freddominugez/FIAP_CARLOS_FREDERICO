// Roteiro de ponta a ponta contra a API publicada (ou outra, com BASE=http://...).
// Cria dados: rodar só em ambiente de demonstração. Uso: node scripts/roteiro-ponta-a-ponta.mjs
const B = (process.env.BASE ?? 'https://oficina-fiap-soat.vercel.app') + '/api/v1';
const ok = (cond, msg) => { console.log((cond ? 'OK   ' : 'FALHA') + ' ' + msg); if (!cond) process.exitCode = 1; };
const req = async (m, u, tok, body, h = {}) => {
  const r = await fetch(B + u, { method: m, headers: { 'content-type': 'application/json', ...(tok ? { authorization: 'Bearer ' + tok } : {}), ...h }, body: body ? JSON.stringify(body) : undefined });
  return { s: r.status, b: await r.json().catch(() => null), h: r.headers };
};
const login = async (email, senha) => (await req('POST', '/auth/login', null, { email, senha })).b?.token;
const admin = await login('admin@oficina.local', 'Oficina@2026');
const atend = await login('atendente@oficina.local', 'Oficina@2026');
const tec = await login('tecnico@oficina.local', 'Oficina@2026');
ok(admin && atend && tec, 'login dos 3 perfis');
const serv = (await req('POST', '/services', admin, { nome: 'Revisão', precoCentavos: 20000 })).b;
const peca = (await req('POST', '/parts', admin, { sku: 'FUM-01', nome: 'Filtro', tipo: 'PECA', unidade: 'UN', precoCentavos: 3500 })).b;
ok((await req('POST', '/parts/' + peca.id + '/movements', admin, { tipo: 'ENTRADA', quantidade: 1 })).s === 201, 'entrada de estoque');
const ana = (await req('POST', '/customers', atend, { documento: '529.982.247-25', nome: 'Ana' })).b;
const beto = (await req('POST', '/customers', atend, { documento: '12.ABC.345/01DE-35', nome: 'Beto Frota' })).b;
ok(beto.documento === '12ABC34501DE35', 'CNPJ alfanumérico');
const carro = (await req('POST', '/vehicles', atend, { clienteId: ana.id, placa: 'abc-1d23', marca: 'Fiat', modelo: 'Argo', ano: 2021 })).b;
const carroB = (await req('POST', '/vehicles', atend, { clienteId: beto.id, placa: 'XYZ9876', marca: 'VW', modelo: 'Gol', ano: 2015 })).b;
await req('POST', '/customers/' + ana.id + '/user', atend, { email: 'ana@cliente.com', senha: 'senha-cliente' });
await req('POST', '/customers/' + beto.id + '/user', atend, { email: 'beto@cliente.com', senha: 'senha-cliente' });
const tAna = await login('ana@cliente.com', 'senha-cliente'); const tBeto = await login('beto@cliente.com', 'senha-cliente');
const abrir = async (c, v) => { let os = (await req('POST', '/orders', atend, { clienteId: c, veiculoId: v, solicitacao: 'Revisão' })).b;
  os = (await req('POST', '/orders/' + os.id + '/diagnosis', tec, { versao: 1 })).b;
  await req('POST', '/orders/' + os.id + '/services', tec, { servicoId: serv.id, quantidade: 1 });
  os = (await req('POST', '/orders/' + os.id + '/parts', tec, { pecaId: peca.id, quantidade: 1 })).b;
  return (await req('POST', '/orders/' + os.id + '/quotes', tec, { versao: os.versao })).b; };
const osA = await abrir(ana.id, carro.id); const osB = await abrir(beto.id, carroB.id);
ok(osA.status === 'AGUARDANDO_APROVACAO' && osA.orcamentos[0].totalCentavos === 23500, 'orçamento publicado: ' + osA.numero + ' R$ 235,00');
const [dA, dB] = await Promise.all([req('POST', '/quotes/' + osA.orcamentos[0].id + '/decision', tAna, { decisao: 'APROVADO' }), req('POST', '/quotes/' + osB.orcamentos[0].id + '/decision', tBeto, { decisao: 'APROVADO' })]);
ok([dA.s, dB.s].sort().join() === '200,409', 'última unidade disputada: ' + [dA.s, dB.s].join(' e '));
const venc = dA.s === 200 ? { os: osA, tok: tAna } : { os: osB, tok: tBeto };
const perd = dA.s === 200 ? tBeto : tAna;
ok((await req('GET', '/me/orders/' + venc.os.id, perd)).s === 404, 'cliente B recebe 404 na OS do cliente A');
let os = (await req('GET', '/orders/' + venc.os.id, atend)).b;
os = (await req('POST', '/orders/' + os.id + '/start', tec, { versao: os.versao })).b;
const linha = os.orcamentos[0].itens.find((i) => i.tipo === 'PECA');
os = (await req('POST', '/orders/' + os.id + '/consumptions', tec, { itemOrcamentoId: linha.id })).b;
os = (await req('POST', '/orders/' + os.id + '/services/' + os.servicos[0].id + '/complete', tec)).b;
os = (await req('POST', '/orders/' + os.id + '/finish', tec, { versao: os.versao })).b;
os = (await req('POST', '/orders/' + os.id + '/deliver', atend, { versao: os.versao })).b;
ok(os.status === 'ENTREGUE' && os.historico.length === 6, 'ciclo completo até ENTREGUE, 6 mudanças no histórico');
const saldo = (await req('GET', '/parts/' + peca.id, admin)).b;
ok(saldo.estoqueFisico === 0 && saldo.estoqueReservado === 0, 'estoque baixado: físico 0, reservado 0');
const hoje = new Date(); const de = new Date(hoje.getTime() - 86400000).toISOString(); const ate = new Date(hoje.getTime() + 86400000).toISOString();
const m = (await req('GET', '/metrics/execution-time?de=' + de + '&ate=' + ate, admin)).b;
ok(m.amostra === 1 && m.mediaSegundos !== null, 'tempo médio: amostra ' + m.amostra + ', ' + m.mediaSegundos + ' s');
ok((await req('GET', '/me/orders', venc.tok)).b.total === 1, 'cliente vê a própria OS em /me/orders');
